def read(p):
    return json.loads(Path(p).read_text())


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def relative(p, root):
    return os.path.relpath(str(p), str(root))


def source_record(p):
    p = p.resolve(strict=True)
    return {'path': str(p), 'size_bytes': p.stat().st_size, 'sha256': sha(p)}


def png_size(p):
    with p.open('rb') as f:
        header = f.read(24)
    if header[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('Unexpected render format: ' + str(p))
    return struct.unpack('>II', header[16:24])


def vertex_count(p):
    with p.open('rb') as f:
        for _ in range(1000):
            line = f.readline().decode('ascii').strip()
            if line.startswith('element vertex '):
                return int(line.split()[-1])
            if line == 'end_header':
                break
    raise ValueError('No vertex count in PLY: ' + str(p))


def native_row(payload, scene):
    if 'per_scene_results' not in payload:
        return payload
    rows = [v for k, v in payload['per_scene_results'].items()
            if k.split('/inpaint/')[0].split('/')[-1] == scene]
    if len(rows) != 1:
        raise ValueError('Ambiguous native metrics: ' + scene)
    return rows[0]


def prepare(report):
    cases = []
    for method, (repository, iteration, label) in METHODS.items():
        repo = BASE / repository
        output = repo / 'output'
        for name in report['common_scenes']:
            if method == 'Inpaint360GS':
                scene = output / 'paper_r4_all_scenes/scenes' / name / 'workspace/output/inpaint360' / name
            else:
                scene = output / 'inpaint360' / name
            correction = next((c for c in report.get('report_corrections', [])
                               if c['method'] == method and c['scene'] == name), None)
            if correction:
                source = Path(correction['source'])
                if sha(source) != correction['sha256']:
                    raise ValueError('Registered source changed: ' + str(source))
                payload = read(source)
                keys = [k for k in payload['per_scene_results']
                        if k.split('/inpaint/')[0].split('/')[-1] == name]
                if len(keys) != 1:
                    raise ValueError('Ambiguous corrected render path')
                final = Path(keys[0])
                if not final.is_absolute():
                    final = next(p for p in source.parents if p.name == 'workspace') / final
                scene = final.parents[2]
            else:
                final = scene / 'inpaint' / label / ('iteration_' + str(iteration))
                source = scene / 'inpaint_evaluation_results.json'
                payload = read(source)
            scene = scene.resolve(strict=True)
            final = final.resolve(strict=True)
            native = native_row(payload, name)
            metrics = {k: float(native[v]) for k, v in {**KEYS, **EXTRA_KEYS}.items()}
            for k in KEYS:
                if not math.isfinite(metrics[k]) or abs(metrics[k] - report['metrics'][method][name][k]) > 1e-6:
                    raise ValueError(f'Metric differs from registered report: {method}/{name}/{k}')
            if method == 'Inpaint360GS':
                model = scene
                ply = model / 'point_cloud_object_inpaint_virtual/iteration_5000/point_cloud.ply'
                workspace = next(p for p in scene.parents if p.name == 'workspace')
                config = workspace / 'config/object_inpaint/inpaint360' / (name + '.json')
            elif method == 'Gaussian Grouping':
                model = scene
                ply = model / 'point_cloud_object_inpaint/iteration_9999/point_cloud.ply'
                config = model / 'cfg_args'
            else:
                native_output = next(p for p in scene.parents if p.name == 'output')
                model = native_output / 'Other-360' / ('inpaint360_' + name)
                ply = model / 'point_cloud/iteration_10000_object_inpaint/point_cloud.ply'
                config = model / 'cfg_args'
            masks = BASE / 'data/Inpaint360GS/inpaint360' / name / 'unseen_mask'
            links = {'final': final, 'renders': final / 'renders', 'gt': final / 'gt', 'masks': masks,
                     'point_cloud.ply': ply, 'config': config, 'native_metrics.json': source}
            for key, candidates in {
                'checkpoints': [model / 'point_cloud'], 'train_views': [model / 'train'],
                'receipts': [model / 'repair_receipts', model / 'reproduction_receipts', model / 'editing_receipts'],
                'camera_mapping.json': [final / 'camera_mapping.json'],
            }.items():
                available = next((p for p in candidates if p.exists()), None)
                if available is not None:
                    links[key] = available
            for p in links.values():
                p.resolve(strict=True)
            renders = sorted((final / 'renders').glob('*.png'))
            if {p.name for p in renders} != {p.name for p in (final / 'gt').glob('*.png')}:
                raise ValueError('Render/GT names differ: ' + str(final))
            if len(renders) != report['test_frame_counts'][name]:
                raise ValueError('Unexpected test frame count: ' + name)
            views = []
            for image in renders:
                dims = png_size(image)
                if dims != png_size(final / 'gt' / image.name):
                    raise ValueError('Render/GT image sizes differ')
                mask = next((masks / (image.stem + ext) for ext in ('.png', '.jpg', '.jpeg', '.JPG')
                             if (masks / (image.stem + ext)).is_file()), None)
                if mask is None:
                    raise ValueError('Missing test mask: ' + image.name)
                views.append({'frame': image.name, 'width': dims[0], 'height': dims[1],
                              'render': 'renders/' + image.name, 'gt': 'gt/' + image.name,
                              'mask': 'masks/' + mask.name})
            cases.append(dict(method=method, name=name, repo=repo, output=output, scene=scene, final=final,
                              model=model.resolve(), ply=ply.resolve(), iteration=iteration,
                              links=links, correction=correction, metrics=metrics, native=native,
                              source=source_record(source), config_record=source_record(config), views=views,
                              vertices=vertex_count(ply), frame_count=len(views)))
    return cases


def preflight_link(path, target):
    if os.path.lexists(str(path)) and (not path.is_symlink() or path.resolve() != target.resolve()):
        raise ValueError('Existing entry would be overwritten: ' + str(path))


def link(path, target):
    preflight_link(path, target)
    if not path.is_symlink():
        path.symlink_to(relative(target.resolve(), path.parent), target_is_directory=target.is_dir())


def text_file(path, content):
    if path.exists() and GENERATED not in path.read_text():
        raise ValueError('Refusing to replace an unrelated document: ' + str(path))
    temporary = path.with_name(path.name + '.tmp')
    temporary.write_text(content)
    os.replace(temporary, path)


def json_file(path, value):
    text_file(path, json.dumps({'generated_by': GENERATED, **value}, ensure_ascii=False, indent=2, allow_nan=False) + '\n')


def csv_file(path, rows, fields, delimiter=','):
    # The first comment identifies this generated index on subsequent runs.
    stream = io.StringIO()
    stream.write('# ' + GENERATED + '\n')
    writer = csv.DictWriter(stream, fieldnames=fields, delimiter=delimiter)
    writer.writeheader(); writer.writerows(rows)
    text_file(path, stream.getvalue())


def metric_table(rows, fields=KEYS):
    keys = list(fields)
    return '\n'.join(['| 场景 / 汇总 | 测试帧 | ' + ' | '.join(keys) + ' |',
                      '|---|---:|' + '---:|' * len(keys)] +
                     ['| ' + r['scene'] + ' | ' + str(r['frames']) + ' | ' +
                      ' | '.join(f'{r[k]:.6f}' for k in keys) + ' |' for r in rows])


def inventory(root, links):
    rows = []
    for parent, dirs, files in os.walk(root, followlinks=False):
        for name in sorted(dirs + files):
            p = Path(parent) / name
            rel = str(p.relative_to(root))
            if p.is_symlink():
                rows.append(dict(path=rel, kind='symlink', bytes=p.lstat().st_size,
                                 target=os.readlink(p)))
            elif p.is_file():
                rows.append(dict(path=rel, kind='file', bytes=p.stat().st_size, target=''))
        dirs[:] = [d for d in dirs if not (Path(parent) / d).is_symlink()]
    return rows


